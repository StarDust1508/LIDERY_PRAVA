-- 040_counting_group_removed.sql
-- Правки заказчика от 11 октября 2026 года: Счётная группа исключена из
-- перечня органов конкурса.
--
-- Что меняется в БД: текст страницы «Оргкомитет и эксперты» — из анонса,
-- основного текста и описания для поиска убирается упоминание Счётной группы.
-- Сам перечень органов и служебный список групп состава живут в сборке публичной
-- части (platform/web/src/pages/OrganizersPage.tsx), поэтому правятся кодом.
--
-- Почему точечная замена, а не запись готового текста: страницу мог отредактировать
-- Оргкомитет в админке после миграции 031 — запись целиком затёрла бы его правки.
-- `replace` снимает только лишнюю фразу и остальное не трогает; условие в `WHERE`
-- делает повторный прогон пустым (фразы уже нет, отметка времени не меняется).
--
-- Почему новый файл, а не правка 031: применённые миграции неизменны, мигратор
-- сверяет их контрольные суммы.
--
-- Что остаётся как есть: значение `experts.stage = 'counting_group'` в
-- ограничении `experts_stage_check` (028). Строк с этим значением нет, снятие
-- значения потребовало бы пересборки ограничения и на публичную часть не влияет:
-- группа больше не выводится ни в перечне органов, ни в составе.
--
-- Срок рассмотрения апелляции (пять рабочих дней) в БД не хранится: по решению
-- заказчика от 8 октября 2026 срок не рассчитывается и пункт снят со страницы
-- сайта (ACCEPTANCE.md, п. 12.1), поэтому тексты страницы «Апелляции» правятся
-- только в сборке. Правило при этом остаётся в пункте 12.4 файла Положения в
-- репозитории (редакция 04.10.2026): расхождение сайта и документа зафиксировано
-- в ACCEPTANCE.md, п. 12.18, решение — за заказчиком.

UPDATE liders.pages
   SET body = replace(body, ' Счётная группа подсчитывает голоса зала на втором (финальном) этапе.', ''),
       excerpt = replace(excerpt, ' и Счётная группа', ''),
       seo_description = replace(seo_description, ' и Счётная группа', ''),
       updated_at = now()
 WHERE slug = 'about-organizers'
   AND (
        body LIKE '%Счётная группа%'
     OR excerpt LIKE '%Счётная группа%'
     OR seo_description LIKE '%Счётная группа%'
   );
