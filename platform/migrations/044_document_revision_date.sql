-- 044_document_revision_date.sql
-- Возвращает дату редакции документов к дате самого документа (04.10.2026).
--
-- Миграция 043 вместе со ссылками на персональные PDF приложений обновила
-- revision_date на дату пересборки (18.10.2026). Это неверно по смыслу: дата
-- редакции — свойство документа, а не даты конвертации. Сверка текста старого и
-- нового PDF показала, что содержание не менялось (26 и 25 страниц, текст
-- совпадает), поэтому возвращаем исходную дату.
--
-- Идемпотентно: UPDATE ... WHERE revision_date <> DATE '2026-10-04'.

UPDATE liders.documents
   SET revision_date = DATE '2026-10-04',
       updated_at = now()
 WHERE type IN ('regulation', 'appendix')
   AND revision_date <> DATE '2026-10-04';
