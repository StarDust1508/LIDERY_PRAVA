-- 030_anonymization_constraints.sql
-- Ограничения, мешавшие удалению персональных данных (ТЗ 11, п. 6).
--
-- Обезличивание по требованию субъекта сначала падало: колонка `birth_date`
-- объявлена обязательной, а после удаления данных даты рождения не существует.
-- Требование «поле заполнено» относится к живой заявке, а не к записи, из
-- которой персональные данные удалены, поэтому ограничение снимается.
--
-- Адрес электронной почты в `participants` тоже обязателен: вместо удаления в
-- него записывается служебная заглушка `erased@invalid.local` — так работает
-- обезличивание, и по адресу видно, что данные удалены.

CREATE SCHEMA IF NOT EXISTS liders;

ALTER TABLE liders.participants
  ALTER COLUMN birth_date DROP NOT NULL;

COMMENT ON COLUMN liders.participants.birth_date IS
  'Дата рождения. NULL после обезличивания по требованию субъекта или по сроку хранения.';
