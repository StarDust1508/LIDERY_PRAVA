-- 6. Материалы первого этапа: ссылка на видеоролик — Приложение № 7 -----------
UPDATE liders.material_requirements
   SET title = 'Ссылка на видеоролик во «ВКонтакте» (Приложение № 7)',
       updated_at = now()
 WHERE season_id = (SELECT id FROM liders.seasons WHERE is_active ORDER BY id DESC LIMIT 1)
   AND stage = 'stage1'
   AND type = 'video_link'
   AND title <> 'Ссылка на видеоролик во «ВКонтакте» (Приложение № 7)';

-- 7. Контроль результата (мигратор выполнит и в случае ошибки откатит) --------
DO $$
DECLARE
  stage1_count int;
  stage1_sum numeric;
BEGIN
  SELECT count(*), coalesce(sum(max_score), 0)
    INTO stage1_count, stage1_sum
    FROM liders.criteria
   WHERE stage = 'stage1' AND is_active;

  IF stage1_count <> 8 OR stage1_sum <> 80 THEN
    RAISE EXCEPTION 'после миграции 041 у первого этапа % критериев и % баллов (ожидалось 8 и 80)',
      stage1_count, stage1_sum;
  END IF;
END $$;
